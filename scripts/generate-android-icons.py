"""Generate Android icons from the canonical Kooyu vector; retain PNG alpha."""
from pathlib import Path
import io
import re
import xml.etree.ElementTree as ET

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "brand/icons/kooyu-app.svg"
RES = ROOT / "apps/android/app/src/main/res"
ANDROID = "http://schemas.android.com/apk/res/android"
SVG = "{http://www.w3.org/2000/svg}"
ET.register_namespace("android", ANDROID)


def generate():
    source = SOURCE.read_bytes()
    svg = ET.fromstring(source)
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        # RGB conversion discards the rounded tile's alpha and turns its corners black.
        png = cairosvg.svg2png(bytestring=source, output_width=size, output_height=size)
        image = Image.open(io.BytesIO(png)).convert("RGBA")
        assert all(image.getpixel(p)[3] == 0 for p in ((0, 0), (size - 1, 0), (0, size - 1), (size - 1, size - 1)))
        destination = RES / f"mipmap-{density}/ic_launcher.png"
        destination.parent.mkdir(parents=True, exist_ok=True)
        image.save(destination)

    # Adaptive artwork is separate from its solid background. The original
    # 512px tile occupies the central 64dp of the 108dp foreground viewport,
    # keeping the white ribbon inside Android's mask-safe area.
    vector = ET.Element("vector", {f"{{{ANDROID}}}{k}": v for k, v in {"width": "108dp", "height": "108dp", "viewportWidth": "108", "viewportHeight": "108"}.items()})
    outer = ET.SubElement(vector, "group", {f"{{{ANDROID}}}{k}": v for k, v in {"translateX": "22", "translateY": "22", "scaleX": "0.125", "scaleY": "0.125"}.items()})
    art = svg.find(f"{SVG}g")
    if art is None:
        raise ValueError("Canonical app icon must contain its foreground group")
    transform = re.fullmatch(r"translate\(([-.\d]+) ([-.\d]+)\) scale\(([-.\d]+)\)", art.attrib.get("transform", ""))
    if transform is None:
        raise ValueError("Unsupported canonical icon transform")
    x, y, scale = transform.groups()
    group = ET.SubElement(outer, "group", {f"{{{ANDROID}}}{k}": v for k, v in {"translateX": x, "translateY": y, "scaleX": scale, "scaleY": scale}.items()})
    paths = art.findall(f"{SVG}path")
    if not paths:
        raise ValueError("Canonical app icon has no foreground paths")
    for path in paths:
        ET.SubElement(group, "path", {f"{{{ANDROID}}}fillColor": path.attrib["fill"], f"{{{ANDROID}}}fillType": "evenOdd" if path.attrib.get("fill-rule") == "evenodd" else "nonZero", f"{{{ANDROID}}}pathData": path.attrib["d"]})
    ET.indent(vector, space="    ")
    destination = RES / "drawable/ic_launcher_foreground.xml"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-android-icons.py from brand/icons/kooyu-app.svg. -->\n' + ET.tostring(vector, encoding="unicode") + "\n", encoding="utf-8")
    print("Generated 5 transparent launcher PNGs and native foreground vector.")


if __name__ == "__main__":
    generate()
