RES = ROOT / "apps/android/app/src/main/res"
SVG_NS = "{http://www.w3.org/2000/svg}"


def extract_ribbon_path(svg_root: ET.Element) -> str:
    for elem in svg_root.iter():
        if elem.tag == f"{SVG_NS}clipPath":
            p = elem.find(f"{SVG_NS}path")
            if p is not None and p.attrib.get("d"):
                return p.attrib["d"]
    for elem in svg_root.iter():
        if elem.tag == f"{SVG_NS}path" and elem.attrib.get("fill-rule") == "evenodd" and elem.attrib.get("d"):
            return elem.attrib["d"]
    raise ValueError("Could not find canonical ribbon silhouette path in kooyu-app.svg")


