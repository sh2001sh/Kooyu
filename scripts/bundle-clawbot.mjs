import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";

// Regenerate from the npm pack tarball for @tencent-weixin/openclaw-weixin@2.4.10.
const archive = resolve(process.argv[2]);
const digest = createHash("sha256").update(readFileSync(archive)).digest("hex");
if (digest !== "69dd18af16a992edbe3700d244f9591ab52f5f58abfe976a9f1250bd8eacdbbb")
  throw Error("Unexpected ClawBot archive");
const temp = mkdtempSync(join(tmpdir(), "kooyu-clawbot-"));
if (dirname(temp) !== resolve(tmpdir())) throw Error("Unexpected extraction directory");
try {
  execFileSync("tar", ["-xf", archive, "-C", temp]);
  const root = join(temp, "package");
  const meta = JSON.parse(readFileSync(join(root, "package.json")));
  const license = readFileSync(join(root, "LICENSE"), "utf8");
  const out = await build({
    stdin: {
      contents:
        'export {getUpdates,sendMessage} from "./dist/src/api/api.js"; export {fetchQRCode,pollQRStatus} from "./dist/src/auth/login-qr.js";',
      resolveDir: root,
    },
    platform: "node",
    target: "node24",
    format: "esm",
    bundle: true,
    write: false,
    plugins: [
      {
        name: "kooyu-host-services",
        setup(b) {
          b.onResolve({ filter: /^kooyu-fetch$/ }, () => ({
            path: "../weixin-transport.js",
            external: true,
          }));
          b.onResolve({ filter: /^qrcode-terminal$/ }, () => ({
            path: "qrcode-terminal",
            external: true,
          }));
          b.onResolve({ filter: /\/accounts\.js$|\/logger\.js$/ }, (a) => ({
            path: a.path,
            namespace: "kooyu",
          }));
          b.onLoad({ filter: /.*/, namespace: "kooyu" }, (a) => ({
            contents: a.path.endsWith("accounts.js")
              ? 'export const listIndexedWeixinAccountIds=()=>[], loadWeixinAccount=()=>undefined, loadConfigRouteTag=()=>undefined, loadConfigBotAgent=()=>"Kooyu/1.0.1";'
              : "const silent=()=>{}; export const logger={debug:silent,info:silent,warn:silent,error:silent};",
          }));
          b.onLoad({ filter: /[\\/]login-qr\.js$/ }, (a) => ({
            contents: readFileSync(a.path, "utf8") + "\nexport {fetchQRCode,pollQRStatus};",
          }));
          b.onLoad({ filter: /[\\/]api[\\/]api\.js$/ }, (a) => {
            const src = readFileSync(a.path, "utf8").replace(
              "const pkg = readPackageJson();",
              "const pkg = " +
                JSON.stringify({ version: meta.version, ilink_appid: meta.ilink_appid }) +
                ";",
            );
            return { contents: 'import {weixinFetch as fetch} from "kooyu-fetch";\n' + src };
          });
        },
      },
    ],
  });
  const body = out.outputFiles[0].text.replace(/^\/\/ .*?(dist\/src\/[^\r\n]+)$/gm, "// $1");
  writeFileSync(
    "packages/host/src/messaging/vendor/clawbot.js",
    "/*!\n" +
      license +
      "\n*/\n// Generated by scripts/bundle-clawbot.mjs from the pinned official plugin.\n" +
      body,
  );
} finally {
  rmSync(temp, { recursive: true, force: true });
}
