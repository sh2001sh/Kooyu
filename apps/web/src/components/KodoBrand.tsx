/** Distinct geometric vector badge for every Harness (`mono` bare icon or `tinted` squircle plate). */
export function HarnessBadge({
  harnessId,
  size = "md",
  shape = "squircle",
  tone = "tinted",
}: {
  harnessId: HarnessId;
  size?: "xs" | "sm" | "md" | "lg";
  shape?: "squircle" | "circle";
  tone?: "tinted" | "mono";
}) {
  const visual = HARNESS_VISUALS[harnessId];
  const glyphSize = size === "lg" ? 26 : size === "md" ? 19 : size === "xs" ? 14 : 16;
  const style = {
    "--badge-tint": visual.tint,
    "--badge-ink": visual.ink,
    "--badge-tint-dark": visual.darkTint,
    "--badge-ink-dark": visual.darkInk,
  } as CSSProperties;

  return (
    <span
      className={`harness-badge harness-badge--${size} harness-badge--${shape} harness-badge--${tone}`}
      data-harness={harnessId}
      style={style}
      aria-hidden="true"
      title={HARNESS_NAMES[harnessId]}
    >
      <HarnessGlyph harnessId={harnessId} size={glyphSize} />
    </span>
  );
}
